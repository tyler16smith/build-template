// Builds the deployable bundle once (`pnpm build` at the root runs the web build first):
//
//   build/
//     worker/index.js (+ .map)   the Worker, bundled by wrangler
//     web/                       the SPA's static assets
//     migrations/                packages/db/migrations, so promote migrates with this build's files
//     wrangler.jsonc             apps/server/wrangler.jsonc, pointed at the files above, no bundling
//     commit.txt                 the commit it was built from
//
// CI uploads `build/` as the staging run's artifact; staging and production deploy that same
// bundle with `wrangler deploy --config build/wrangler.jsonc --env <env> --tag <sha>`.
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const server = join(here, "..");
const root = join(server, "../..");
const out = join(root, "build");
const web = join(root, "apps/web/dist");

if (!existsSync(join(web, "index.html")))
  throw new Error("Build the web app first (pnpm --filter @template/web build, or pnpm build).");

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

execFileSync(
  "pnpm",
  [
    "exec",
    "wrangler",
    "deploy",
    "--dry-run",
    "--outdir",
    join(out, "worker"),
    "--config",
    "wrangler.jsonc",
  ],
  { cwd: server, stdio: "inherit" },
);
cpSync(web, join(out, "web"), { recursive: true });
cpSync(join(root, "packages/db/migrations"), join(out, "migrations"), { recursive: true });

const config = readFileSync(join(server, "wrangler.jsonc"), "utf8");
const replace = (text, from, to) => {
  if (!text.includes(from)) throw new Error(`wrangler.jsonc no longer contains ${from}`);
  return text.replace(from, to);
};
let built = replace(
  config,
  '"main": "src/index.ts",',
  '"main": "worker/index.js",\n  "no_bundle": true,',
);
built = replace(built, '"directory": "../web/dist",', '"directory": "web",');
built = replace(built, '"$schema": "../../node_modules/wrangler/config-schema.json",', "");
writeFileSync(
  join(out, "wrangler.jsonc"),
  `// Generated by apps/server/scripts/build.mjs. Don't edit.\n${built}`,
);

let commit = process.env.GITHUB_SHA ?? "";
if (!commit)
  try {
    commit = execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    commit = "local";
  }
writeFileSync(join(out, "commit.txt"), `${commit}\n`);
console.log(`built ${out} (${commit})`);
